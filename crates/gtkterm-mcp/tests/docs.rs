//! The tool reference at the end of `docs/mcp.md` is generated from the server's schemas.
//! Run `UPDATE_DOCS=1 cargo test -p gtkterm-mcp --test docs` after changing a tool.
#![allow(clippy::unwrap_used)]

use std::fmt::Write as _;

use gtkterm_core::config::Config;
use gtkterm_core::manager::SessionManager;
use gtkterm_mcp::{GtkTermMcp, ServerOptions};
use serde_json::Value;

const BEGIN: &str = "<!-- tool-reference:begin (generated by crates/gtkterm-mcp/tests/docs.rs) -->";
const END: &str = "<!-- tool-reference:end -->";

/// A short type name for a JSON schema.
fn type_name(schema: &Value) -> String {
    if let Some(r) = schema.get("$ref").and_then(Value::as_str) {
        return r.rsplit('/').next().unwrap_or(r).to_owned();
    }
    if let Some(t) = schema.get("type") {
        return match t {
            Value::Array(ts) => ts
                .iter()
                .filter_map(Value::as_str)
                .filter(|t| *t != "null")
                .collect::<Vec<_>>()
                .join(" | "),
            Value::String(t) if t == "array" => {
                format!("{}[]", schema.get("items").map_or_else(String::new, type_name))
            }
            Value::String(t) => t.clone(),
            _ => String::new(),
        };
    }
    for key in ["anyOf", "oneOf"] {
        if let Some(Value::Array(alts)) = schema.get(key) {
            return alts
                .iter()
                .map(type_name)
                .filter(|t| t != "null")
                .collect::<Vec<_>>()
                .join(" | ");
        }
    }
    String::new()
}

fn first_sentence(text: &str) -> String {
    let text = text.split_whitespace().collect::<Vec<_>>().join(" ");
    match text.find(". ") {
        Some(i) => text[..=i].to_owned(),
        None => text,
    }
}

fn reference(schema: &Value) -> String {
    let writes: Vec<&str> = schema["write_tools"]
        .as_array()
        .unwrap()
        .iter()
        .filter_map(Value::as_str)
        .collect();
    let mut tools: Vec<&Value> = schema["tools"].as_array().unwrap().iter().collect();
    tools.sort_by_key(|t| t["name"].as_str().unwrap_or_default().to_owned());
    let mut out =
        String::from("| Tool | Write | Parameters (`*` required) | Description |\n|---|---|---|---|\n");
    for t in tools {
        let name = t["name"].as_str().unwrap();
        let input = &t["inputSchema"];
        let required: Vec<&str> = input["required"]
            .as_array()
            .map(|r| r.iter().filter_map(Value::as_str).collect())
            .unwrap_or_default();
        let params: Vec<String> = input["properties"]
            .as_object()
            .map(|props| {
                props
                    .iter()
                    .map(|(p, s)| {
                        let star = if required.contains(&p.as_str()) { "*" } else { "" };
                        format!("`{p}`{star} {}", type_name(s))
                    })
                    .collect()
            })
            .unwrap_or_default();
        let _ = writeln!(
            out,
            "| `{name}` | {} | {} | {} |",
            if writes.contains(&name) { "yes" } else { "" },
            params.join(", "),
            first_sentence(t["description"].as_str().unwrap_or_default()).replace('|', "\\|"),
        );
    }
    out
}

#[test]
fn tool_reference_in_docs_is_current() {
    let manager = SessionManager::new(Config::default(), None);
    let schema = GtkTermMcp::new(manager, ServerOptions::default()).schema();
    let generated = reference(&schema);
    let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../../docs/mcp.md");
    let doc = std::fs::read_to_string(path).unwrap();
    let start = doc.find(BEGIN).expect("begin marker in docs/mcp.md") + BEGIN.len();
    let end = doc.find(END).expect("end marker in docs/mcp.md");
    let current = doc[start..end].trim();
    if current == generated.trim() {
        return;
    }
    if std::env::var_os("UPDATE_DOCS").is_some() {
        let updated = format!("{}\n{}{}", &doc[..start], generated, &doc[end..]);
        std::fs::write(path, updated).unwrap();
        return;
    }
    panic!(
        "docs/mcp.md tool reference is out of date; run UPDATE_DOCS=1 cargo test -p gtkterm-mcp --test docs"
    );
}

#[test]
fn schema_lists_every_tool_with_an_input_schema() {
    let manager = SessionManager::new(Config::default(), None);
    let schema = GtkTermMcp::new(manager, ServerOptions::default()).schema();
    let tools = schema["tools"].as_array().unwrap();
    for t in tools {
        assert_eq!(t["inputSchema"]["type"], "object", "{}", t["name"]);
        assert!(
            !t["description"].as_str().unwrap_or_default().is_empty(),
            "{} has no description",
            t["name"]
        );
    }
    for t in tools {
        // MCP requires object output schemas; clients drop tools whose schema is anything else
        // (the Inspector listed only 26 of 44 tools while 18 returned a bare `Value`).
        if let Some(out) = t.get("outputSchema") {
            assert_eq!(out["type"], "object", "{} output schema: {out}", t["name"]);
        }
        // Optional parameters are plain types, not `[type, null]` (portable to single-type dialects).
        let required: Vec<&Value> = t["inputSchema"]["required"]
            .as_array()
            .map(|r| r.iter().collect())
            .unwrap_or_default();
        for (name, p) in t["inputSchema"]["properties"].as_object().unwrap() {
            if required.iter().any(|r| r.as_str() == Some(name)) {
                continue;
            }
            let text = p.to_string();
            assert!(
                !text.contains("\"null\""),
                "{}.{name} is nullable: {text}",
                t["name"]
            );
        }
    }
    for w in schema["write_tools"].as_array().unwrap() {
        assert!(
            tools.iter().any(|t| t["name"] == *w),
            "write tool {w} does not exist"
        );
    }
    insta::assert_yaml_snapshot!(schema["tools"]);
}
