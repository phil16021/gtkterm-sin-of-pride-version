//! Translation catalogue: extract marked strings from the GUI sources into
//! `po/gtkterm-sunshine.pot`, merge them into the `.po` files, compile `.mo` files.
//!
//! Rust strings are found with a tokenizer (xgettext before 0.24 cannot read Rust): the
//! first string literal argument of `gettext(…)`, `gettext_f(…)` and `n_!(…)`, and the first
//! two of `ngettext_f(…)`. Desktop file and metainfo strings come from `xgettext`.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{Context, Result, bail};
use proc_macro2::{Delimiter, TokenStream, TokenTree};

pub(crate) const DOMAIN: &str = "gtkterm-sunshine";
const SOURCES: &str = "crates/gtkterm-gui/src";
const DATA: [&str; 2] = [
    "data/at.philipp.GtkTermSunshine.desktop",
    "data/at.philipp.GtkTermSunshine.metainfo.xml",
];

/// One message: id, optional plural, source references.
#[derive(Debug, Default)]
struct Msg {
    plural: Option<String>,
    refs: Vec<String>,
}

fn rust_files(dir: &Path, out: &mut Vec<PathBuf>) -> Result<()> {
    let mut entries: Vec<_> = std::fs::read_dir(dir)?.collect::<Result<_, _>>()?;
    entries.sort_by_key(std::fs::DirEntry::path);
    for e in entries {
        let p = e.path();
        if p.is_dir() {
            rust_files(&p, out)?;
        } else if p.extension().is_some_and(|x| x == "rs") {
            out.push(p);
        }
    }
    Ok(())
}

fn string_literal(tt: &TokenTree) -> Option<String> {
    let TokenTree::Literal(lit) = tt else { return None };
    match syn::Lit::new(lit.clone()) {
        syn::Lit::Str(s) => Some(s.value()),
        _ => None,
    }
}

/// Walk `tokens`, recording marked strings in `msgs` (in order of first appearance).
fn scan(tokens: TokenStream, file: &str, order: &mut Vec<String>, msgs: &mut BTreeMap<String, Msg>) {
    let tts: Vec<TokenTree> = tokens.into_iter().collect();
    let mut i = 0;
    while i < tts.len() {
        // Test modules are not shipped.
        if let (TokenTree::Ident(m), Some(TokenTree::Ident(t))) = (&tts[i], tts.get(i + 1))
            && m == "mod"
            && t == "tests"
        {
            i += 3;
            continue;
        }
        if let TokenTree::Ident(id) = &tts[i] {
            let name = id.to_string();
            let is_def = i > 0 && matches!(&tts[i - 1], TokenTree::Ident(f) if f == "fn");
            let mut j = i + 1;
            if name == "n_" && matches!(tts.get(j), Some(TokenTree::Punct(p)) if p.as_char() == '!') {
                j += 1;
            }
            let wanted = matches!(name.as_str(), "gettext" | "gettext_f" | "ngettext_f" | "n_");
            if wanted
                && !is_def
                && let Some(TokenTree::Group(g)) = tts.get(j)
                && g.delimiter() == Delimiter::Parenthesis
            {
                let args: Vec<TokenTree> = g.stream().into_iter().collect();
                if let Some(id) = args.first().and_then(string_literal) {
                    let plural = if name == "ngettext_f" {
                        args.get(2).and_then(string_literal)
                    } else {
                        None
                    };
                    let line = id_line(&args[0]);
                    let entry = msgs.entry(id.clone()).or_insert_with(|| {
                        order.push(id.clone());
                        Msg::default()
                    });
                    if entry.plural.is_none() {
                        entry.plural = plural;
                    }
                    entry.refs.push(format!("{file}:{line}"));
                }
            }
        }
        if let TokenTree::Group(g) = &tts[i] {
            scan(g.stream(), file, order, msgs);
        }
        i += 1;
    }
}

fn id_line(tt: &TokenTree) -> usize {
    tt.span().start().line
}

fn po_string(s: &str) -> String {
    let esc = |s: &str| {
        s.replace('\\', "\\\\")
            .replace('"', "\\\"")
            .replace('\t', "\\t")
            .replace('\r', "\\r")
            .replace('\n', "\\n")
    };
    if s.contains('\n') && s.trim_end_matches('\n').contains('\n') {
        let mut out = String::from("\"\"\n");
        for part in s.split_inclusive('\n') {
            let _ = writeln!(out, "\"{}\"", esc(part));
        }
        out.pop();
        out
    } else {
        format!("\"{}\"", esc(s))
    }
}

const HEADER: &str = r#"# Translation template for GTKTerm Sunshine.
# This file is distributed under the same license as the gtkterm-sunshine package.
# Generated by `cargo xtask po`; do not edit. Placeholders in braces ({port}) must be kept.
#
#, fuzzy
msgid ""
msgstr ""
"Project-Id-Version: gtkterm-sunshine\n"
"Report-Msgid-Bugs-To: \n"
"PO-Revision-Date: YEAR-MO-DA HO:MI+ZONE\n"
"Last-Translator: FULL NAME <EMAIL@ADDRESS>\n"
"Language-Team: LANGUAGE <LL@li.org>\n"
"Language: \n"
"MIME-Version: 1.0\n"
"Content-Type: text/plain; charset=UTF-8\n"
"Content-Transfer-Encoding: 8bit\n"
"Plural-Forms: nplurals=INTEGER; plural=EXPRESSION;\n"
"#;

/// The template for the Rust sources.
fn rust_template(root: &Path) -> Result<String> {
    let mut files = Vec::new();
    rust_files(&root.join(SOURCES), &mut files)?;
    let mut order = Vec::new();
    let mut msgs = BTreeMap::new();
    for f in &files {
        let text = std::fs::read_to_string(f)?;
        let tokens: TokenStream = text
            .parse()
            .map_err(|e| anyhow::anyhow!("{}: {e:?}", f.display()))?;
        let rel = f.strip_prefix(root).unwrap_or(f).display().to_string();
        scan(tokens, &rel, &mut order, &mut msgs);
    }
    let mut out = String::from(HEADER);
    for id in order {
        let m = &msgs[&id];
        out.push('\n');
        if id.contains('{') {
            out.push_str("#, rust-format\n");
        }
        for r in &m.refs {
            let _ = writeln!(out, "#: {r}");
        }
        let _ = writeln!(out, "msgid {}", po_string(&id));
        match &m.plural {
            Some(p) => {
                let _ = writeln!(out, "msgid_plural {}", po_string(p));
                out.push_str("msgstr[0] \"\"\nmsgstr[1] \"\"\n");
            }
            None => out.push_str("msgstr \"\"\n"),
        }
    }
    Ok(out)
}

fn have(tool: &str) -> bool {
    Command::new(tool)
        .arg("--version")
        .output()
        .is_ok_and(|o| o.status.success())
}

fn tool(cmd: &mut Command) -> Result<()> {
    let out = cmd.output().with_context(|| format!("spawning {cmd:?}"))?;
    if !out.status.success() {
        bail!("{cmd:?} failed: {}", String::from_utf8_lossy(&out.stderr));
    }
    Ok(())
}

/// The complete template (Rust sources, desktop file, metainfo).
pub(crate) fn template(root: &Path) -> Result<String> {
    let rust = rust_template(root)?;
    if !have("xgettext") {
        bail!("xgettext (gettext) is required");
    }
    let tmp = root.join("target/xtask-po");
    std::fs::create_dir_all(&tmp)?;
    let rust_pot = tmp.join("rust.pot");
    let data_pot = tmp.join("data.pot");
    let all = tmp.join("all.pot");
    std::fs::write(&rust_pot, rust)?;
    tool(
        Command::new("xgettext")
            .current_dir(root)
            .args(["--from-code=UTF-8", "--omit-header", "--no-wrap", "-o"])
            .arg(&data_pot)
            .args(DATA),
    )?;
    tool(
        Command::new("msgcat")
            .args(["--use-first", "--no-wrap", "-o"])
            .arg(&all)
            .arg(&rust_pot)
            .arg(&data_pot),
    )?;
    Ok(std::fs::read_to_string(all)?)
}

/// Languages listed in `po/LINGUAS`.
pub(crate) fn languages(root: &Path) -> Vec<String> {
    let text = std::fs::read_to_string(root.join("po/LINGUAS")).unwrap_or_default();
    text.lines()
        .map(|l| l.split('#').next().unwrap_or("").trim())
        .flat_map(str::split_whitespace)
        .map(str::to_owned)
        .collect()
}

/// `cargo xtask po`: write the template and merge it into every translation.
pub(crate) fn update(root: &Path) -> Result<()> {
    let pot = root.join(format!("po/{DOMAIN}.pot"));
    std::fs::write(&pot, template(root)?)?;
    eprintln!("wrote {}", pot.display());
    for lang in languages(root) {
        let po = root.join(format!("po/{lang}.po"));
        if !po.exists() {
            tool(
                Command::new("msginit")
                    .args(["--no-translator", "--no-wrap", "-l", &lang, "-i"])
                    .arg(&pot)
                    .arg("-o")
                    .arg(&po),
            )?;
        }
        tool(
            Command::new("msgmerge")
                .args(["--quiet", "--update", "--backup=none", "--no-wrap", "--previous"])
                .arg(&po)
                .arg(&pot),
        )?;
        let out = Command::new("msgfmt")
            .args(["--statistics", "-o", "/dev/null"])
            .arg(&po)
            .output()?;
        eprintln!("{lang}: {}", String::from_utf8_lossy(&out.stderr).trim());
    }
    Ok(())
}

/// `cargo xtask check`: the template is current and every translation compiles.
pub(crate) fn check(root: &Path) -> Result<()> {
    if !have("xgettext") || !have("msgfmt") {
        eprintln!("note: gettext tools missing, skipping the translation check");
        return Ok(());
    }
    let committed = std::fs::read_to_string(root.join(format!("po/{DOMAIN}.pot"))).unwrap_or_default();
    if committed != template(root)? {
        bail!("po/{DOMAIN}.pot is out of date: run `cargo xtask po`");
    }
    for lang in languages(root) {
        tool(
            Command::new("msgfmt")
                .args(["--check", "-o", "/dev/null"])
                .arg(root.join(format!("po/{lang}.po"))),
        )?;
    }
    eprintln!("translations ok");
    Ok(())
}

/// Compile `po/<lang>.po` into `<share>/locale/<lang>/LC_MESSAGES/gtkterm-sunshine.mo`.
pub(crate) fn compile(root: &Path, share: &Path) -> Result<Vec<PathBuf>> {
    let mut out = Vec::new();
    for lang in languages(root) {
        let mo = share.join(format!("locale/{lang}/LC_MESSAGES/{DOMAIN}.mo"));
        if let Some(d) = mo.parent() {
            std::fs::create_dir_all(d)?;
        }
        tool(
            Command::new("msgfmt")
                .arg("-o")
                .arg(&mo)
                .arg(root.join(format!("po/{lang}.po"))),
        )?;
        out.push(mo);
    }
    Ok(out)
}

/// Merge the translations into the desktop file or metainfo (`--desktop` / `--xml`).
pub(crate) fn translate_data(root: &Path, kind: &str, template: &Path, out: &Path) -> Result<()> {
    tool(
        Command::new("msgfmt")
            .arg(kind)
            .arg("--template")
            .arg(template)
            .arg("-d")
            .arg(root.join("po"))
            .arg("-o")
            .arg(out),
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn finds_marked_strings_only() {
        let src = r#"
            fn gettext(s: &str) -> String { s.into() }
            fn f() {
                let a = gettext("Open \"port\"");
                b.set_label(&gettext_f("Port {port}", &[("port", &p)]));
                let n = ngettext_f("{n} file", "{n} files", n, &[]);
                const T: &str = crate::n_!("Copy");
                let dynamic = gettext(x.label());
                let other = foo("Not marked");
                let again = gettext("Open \"port\"");
            }
            mod tests { fn t() { gettext("test only"); } }
        "#;
        let mut order = Vec::new();
        let mut msgs = BTreeMap::new();
        scan(src.parse().unwrap(), "x.rs", &mut order, &mut msgs);
        assert_eq!(order, ["Open \"port\"", "Port {port}", "{n} file", "Copy"]);
        assert_eq!(msgs["Open \"port\""].refs, ["x.rs:4", "x.rs:10"]);
        assert_eq!(msgs["{n} file"].plural.as_deref(), Some("{n} files"));
        assert_eq!(po_string("a\"b\\"), r#""a\"b\\""#);
        assert_eq!(po_string("one\ntwo"), "\"\"\n\"one\\n\"\n\"two\"");
    }
}
